def test_fresh_original_FINAL_completepacket(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    value = prepared_two_tasks(tmp_path, monkeypatch)
    initial_config8(value)
    state = Path(value["state"])
    assert not (state / "invocations").exists()
    roles(value)
    script = state / "synthetic-roles.py"
    text = script.read_text()
    old = "if fields['issue']==301: (root/'code.py').write_text('VALUE = 2\\n')"
    new = (
        "(root/'code.py').write_text('VALUE = '+"
        "str({301:2,303:3}[fields['issue']])+'\\n')"
    )
    assert text.count(old) == 1
    script.write_text(text.replace(old, new))
    harness = state / "fresh-final-collector.py"
    harness.write_text(
        "import sys,json\nfrom pathlib import Path\n"
        + "sys.path.insert(0,"
        + repr(str(Path(value["installed"]) / "policy"))
        + ")\n"
        + "from tools.agent_learning_evidence import SourceReader\n"
        + "state=Path("
        + repr(str(state))
        + ")\n"
        + "root=Path("
        + repr(value["root"])
        + ")\n"
        + "source=Path("
        + repr(str(Path.cwd()))
        + ")\n"
        + "reader=SourceReader(state,root)\n"
        + "REMOTE="
        + repr(value["remote"])
        + "\n"
        + preaggregate_at_driver_preflight(BODY, collector=True)
        + "\n"
    )

    def retain_child_streams(
        stdout: str | bytes | None, stderr: str | bytes | None
    ) -> None:
        for name, value in (
            ("collector-child.stdout", stdout),
            ("collector-child.stderr", stderr),
        ):
            data = (
                value
                if isinstance(value, bytes)
                else (value or "").encode("utf-8", "surrogatepass")
            )
            descriptor = os.open(
                state / name, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600
            )
            with os.fdopen(descriptor, "wb") as stream:
                stream.write(data)

    try:
        run = subprocess.run(
            [sys.executable, "-B", str(harness)],
            capture_output=True,
            text=True,
            timeout=660,
        )
    except subprocess.TimeoutExpired as error:
        try:
            retain_child_streams(error.stdout, error.stderr)
        except BaseException:
            # Evidence is best effort; preserve this exact original timeout.
            pass
        raise
    retain_child_streams(run.stdout, run.stderr)
    assert run.returncode == 0, run.stderr + run.stdout
    lines = run.stdout.splitlines()
    assert lines[:4] == [
        "HISTORY_COMPLETE",
        "COLLECTOR_MISSING_BINDING_BEGIN",
        "COLLECTOR_POSITIVE_BEGIN",
        "COLLECTOR_POSITIVE_RETURNED",
    ]
    assert lines[4] == "COLLECTOR_OUTSIDE_FINAL_BEGIN"
    result = json.loads(lines[5])
    assert len(lines) == 6
    assert result["collector_calls"] == 3 and result["aggregate_calls"] == 0
    assert result["faults"] == ["missing-binding", "outside-final-stage"]
    assert len(result["packet"]["calls"]) == 6
    assert [row["task"] for row in result["packet"]["tasks"]] == [301, 303]
